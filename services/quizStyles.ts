/** 配列をシャッフルした新しい配列を返す（Fisher–Yates） */
export const shuffled = <T,>(items: readonly T[], random: () => number = Math.random): T[] => {
  const arr = [...items];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
};

/**
 * count問分のスタイルを割り当てる。スタイル数以上の問題数でも、
 * 同じスタイルが連続・偏らないよう、一巡するまで重複させない。
 */
export const assignQuizStyles = (
  count: number,
  random: () => number = Math.random
): QuizStyle[] => {
  const result: QuizStyle[] = [];
  while (result.length < count) {
    result.push(...shuffled(QUIZ_STYLES, random));
  }
  return result.slice(0, count);
};
